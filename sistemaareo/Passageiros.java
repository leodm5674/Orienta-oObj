package atividade;

public class Passageiros {
    private String nome;
    private int idade;
    private char sexo;
    private int cpf;

    public String getNome(){
        return this.nome;
    }

    public int getIdade() {
        return this.idade;
    }

    public char getSexo() {
        return this.sexo;
    }

    public int getCpf() {
        return this.cpf;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public void setIdade(int idade) {
        this.idade = idade;
    }

    public void setSexo(char sexo) {
        this.sexo = sexo;
    }

    public void setCpf(int cpf) {
        this.cpf = cpf;
    }
    




    
}
